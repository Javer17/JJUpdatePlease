// e.g. "Aberafan Maesteg" -> "Aberafan-Maesteg"
function ukConstituencyID(name)
{
  return name.replace(/ /g, "-")
}

// Builds the {names, ids, nameToID, idToName} lookups for one list of constituency names.
function buildUKConstituencyLookups(names)
{
  return {
    names: names,
    ids: names.map(ukConstituencyID),
    nameToID: Object.fromEntries(names.map(name => [name, ukConstituencyID(name)])),
    idToName: Object.fromEntries(names.map(name => [ukConstituencyID(name), name]))
  }
}

// Returns the constituency lookups that apply to a given year: the lookups for the most
// recent boundary set in UKConstituenciesByYear at or before that year (falling back to
// the earliest defined set for years before it). Add a new "year: [...]" entry to
// UKConstituenciesByYear below whenever boundaries change - this picks it up automatically,
// no other code needs to change.
function getUKConstituencyLookupsForYear(year)
{
  const definedYears = Object.keys(UKConstituenciesByYear).map(Number).sort((a, b) => a - b)
  const applicableYear = [...definedYears].reverse().find(definedYear => definedYear <= year) ?? definedYears[0]
  return UKConstituencyLookupsByYear[applicableYear]
}

